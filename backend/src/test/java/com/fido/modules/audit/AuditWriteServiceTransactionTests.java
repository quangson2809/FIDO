@ExtendWith(SpringExtension.class)
@ContextConfiguration(classes = AuditWriteServiceTransactionTests.TestConfiguration.class)
class AuditWriteServiceTransactionTests {

    @Autowired private JdbcTemplate jdbc;
    @Autowired private PlatformTransactionManager transactionManager;
    @Autowired private AuditWriteService writer;

    @BeforeEach
    void createTargetSchemaFixture() {
        jdbc.execute("DROP TABLE IF EXISTS audit_logs");
        jdbc.execute("DROP TABLE IF EXISTS business_probe");
        jdbc.execute("DROP TABLE IF EXISTS accounts");
        jdbc.execute("CREATE TABLE accounts (id BIGINT PRIMARY KEY)");
        jdbc.execute(
                """
                CREATE TABLE audit_logs (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actor_account_id BIGINT NULL,
                    action VARCHAR(120) NOT NULL,
                    entity_type VARCHAR(80) NOT NULL,
                    entity_id VARCHAR(100) NOT NULL,
                    before_data JSON NULL,
                    after_data JSON NULL,
                    correlation_id VARCHAR(120) NULL,
                    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
                    CONSTRAINT fk_audit_logs_actor FOREIGN KEY (actor_account_id) REFERENCES accounts(id),
                    CONSTRAINT ck_audit_write_failure CHECK (action <> 'ORDER_CANCEL')
                )
                """);
        jdbc.execute("CREATE TABLE business_probe (id BIGINT PRIMARY KEY)");
        jdbc.update("INSERT INTO accounts(id) VALUES (?)", 7L);
    }

    @AfterEach
    void clearContexts() {
        SecurityContextHolder.clearContext();
        CorrelationIdContext.clear();
    }

    @Test
    void writesTargetColumnsWithPrincipalActorCorrelationAndAllowlistedPayloads() {
        authenticateAs(7L);
        AuditWriteEvent event =
                AuditWriteEvent.withChanges(
                        AuditAction.CONTENT_UPDATE,
                        AuditEntityType.CONTENT_PAGE,
                        "42",
                        Map.of(
                                "status", "DRAFT",
                                "title", "Safe title",
                                "password", "never-store-this-marker",
                                "nested", Map.of("token", "nested-secret-marker")),
                        Map.of(
                                "status", "PUBLISHED",
                                "title", "Updated title",
                                "authorization", "Bearer never-store-this-marker"));

        try (CorrelationIdContext.Scope ignored = CorrelationIdContext.open(" trace:request-42 ")) {
            new TransactionTemplate(transactionManager)
                    .execute(
                            status -> {
                                jdbc.update("INSERT INTO business_probe(id) VALUES (?)", 11L);
                                writer.record(event);
                                writer.record(
                                        AuditWriteEvent.withChanges(
                                                AuditAction.PRODUCT_UPDATE,
                                                AuditEntityType.PRODUCT,
                                                "43",
                                                Map.of("status", "DRAFT"),
                                                Map.of("status", "PUBLISHED")));
                                return null;
                            });
        }

        assertEquals(
                2,
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM audit_logs WHERE actor_account_id = 7",
                        Integer.class));
        assertEquals(
                2,
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM audit_logs WHERE correlation_id = 'trace:request-42'",
                        Integer.class));
        assertEquals(
                "CONTENT_PAGE",
                jdbc.queryForObject(
                        "SELECT entity_type FROM audit_logs WHERE entity_id = '42'",
                        String.class));
        assertEquals(
                "trace:request-42",
                jdbc.queryForObject(
                        "SELECT correlation_id FROM audit_logs WHERE entity_id = '42'",
                        String.class));

        String beforeJson =
                jdbc.queryForObject(
                        "SELECT before_data FROM audit_logs WHERE entity_id = '42'",
                        String.class);
        String afterJson =
                jdbc.queryForObject(
                        "SELECT after_data FROM audit_logs WHERE entity_id = '42'",
                        String.class);
        assertTrue(beforeJson.contains("\"status\":\"DRAFT\""));
        assertFalse(beforeJson.contains("Safe title"));
        assertFalse(beforeJson.contains("never-store-this-marker"));
        assertFalse(beforeJson.contains("nested-secret-marker"));
        assertTrue(afterJson.contains("\"status\":\"PUBLISHED\""));
        assertFalse(afterJson.contains("never-store-this-marker"));
        assertFalse(afterJson.contains("Updated title"));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM business_probe", Integer.class));
    }

    @Test
    void failedAuditInsertRollsBackTheCallersBusinessWrite() {
        authenticateAs(7L);
        try (CorrelationIdContext.Scope ignored = CorrelationIdContext.open("trace:rollback")) {
            assertThrows(
                    DataAccessException.class,
                    () ->
                            new TransactionTemplate(transactionManager)
                                    .execute(
                                            status -> {
                                                jdbc.update(
                                                        "INSERT INTO business_probe(id) VALUES (?)",
                                                        12L);
                                                writer.record(
                                                        AuditWriteEvent.of(
                                                                AuditAction.ORDER_CANCEL,
                                                                AuditEntityType.ORDER,
                                                                "99"));
                                                return null;
                                            }));
        }

        assertEquals(
                0,
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM business_probe WHERE id = 12", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM audit_logs", Integer.class));
    }

    @Test
    void humanAuditRequiresAnExistingCallerTransaction() {
        authenticateAs(7L);
        assertThrows(
                IllegalTransactionStateException.class,
                () ->
                        writer.record(
                                AuditWriteEvent.of(
                                        AuditAction.ORDER_CREATE,
                                        AuditEntityType.ORDER,
                                        "99")));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM audit_logs", Integer.class));
    }

    @Test
    void trustedSystemEventUsesNullActorAndGeneratedCorrelation() {
        SecurityContextHolder.clearContext();

        try (CorrelationIdContext.Scope ignored = CorrelationIdContext.openGenerated()) {
            new TransactionTemplate(transactionManager)
                    .execute(
                            status -> {
                                writer.recordSystemEvent(
                                        AuditWriteEvent.withChanges(
                                                AuditAction.CONTENT_CREATE,
                                                AuditEntityType.CONTENT_PAGE,
                                                "88",
                                                Map.of(),
                                                Map.of("status", "DRAFT", "title", "System page")));
                                return null;
                            });
        }

        assertEquals(
                1,
                jdbc.queryForObject(
                        "SELECT COUNT(*) FROM audit_logs WHERE actor_account_id IS NULL",
                        Integer.class));
        String correlationId =
                jdbc.queryForObject(
                        "SELECT correlation_id FROM audit_logs", String.class);
        assertTrue(correlationId.matches("[A-Za-z0-9._:-]{1,120}"));
    }

    private void authenticateAs(long accountId) {
        Instant now = Instant.now();
        Jwt jwt =
                Jwt.withTokenValue("test-only-token")
                        .header("alg", "none")
                        .subject(Long.toString(accountId))
                        .issuedAt(now.minusSeconds(1))
                        .expiresAt(now.plusSeconds(60))
                        .build();
        var context = SecurityContextHolder.createEmptyContext();
        context.setAuthentication(
                new JwtAuthenticationToken(
                        jwt, List.of(new SimpleGrantedAuthority("ROLE_ADMIN"))));
        SecurityContextHolder.setContext(context);
    }

    @Configuration
    @EnableTransactionManagement
    static class TestConfiguration {

        @Bean
        DataSource dataSource() {
            DriverManagerDataSource dataSource = new DriverManagerDataSource();
            dataSource.setDriverClassName("org.h2.Driver");
            dataSource.setUrl("jdbc:h2:mem:audit-write-core;MODE=MySQL;DB_CLOSE_DELAY=-1");
            dataSource.setUsername("sa");
            dataSource.setPassword("");
            return dataSource;
        }

        @Bean
        JdbcTemplate jdbcTemplate(DataSource dataSource) {
            return new JdbcTemplate(dataSource);
        }

        @Bean
        PlatformTransactionManager transactionManager(DataSource dataSource) {
            return new DataSourceTransactionManager(dataSource);
        }

        @Bean
        ObjectMapper objectMapper() {
            return new ObjectMapper();
        }

        @Bean
        AuditWriteRepository auditWriteRepository(JdbcTemplate jdbcTemplate) {
            return new AuditWriteRepository(jdbcTemplate);
        }

        @Bean
        AuditActorResolver auditActorResolver() {
            return new AuditActorResolver();
        }

        @Bean
        AuditPayloadPolicy auditPayloadPolicy(ObjectMapper objectMapper) {
            return new AuditPayloadPolicy(objectMapper);
        }

        @Bean
        AuditWriteService auditWriteService(
                AuditWriteRepository repository,
                AuditActorResolver resolver,
                AuditPayloadPolicy payloadPolicy) {
            return new AuditWriteService(repository, resolver, payloadPolicy);
        }
    }
}
